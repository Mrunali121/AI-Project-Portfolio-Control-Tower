"""
End-to-end pipeline:  CSV data -> metrics -> facts -> (LLM) report -> dashboard data.

    python src/run_pipeline.py                      # auto-detect provider, else offline
    python src/run_pipeline.py --provider offline
    python src/run_pipeline.py --provider anthropic # needs ANTHROPIC_API_KEY
    python src/run_pipeline.py --provider openai    # needs OPENAI_API_KEY and OPENAI_MODEL

Writes
    data/processed/*.csv           tables for Power BI (metrics already calculated)
    outputs/portfolio_facts.json   the facts the report writer sees
    reports/generated-report.md    the report (provider named in the footer)
    data.js                        data for the web dashboard (index.html)
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import metrics as M                      # noqa: E402
import report_generator as G             # noqa: E402

ROOT = M.ROOT


def load_dotenv(path: Path = ROOT / ".env") -> None:
    if path.exists():
        for line in path.read_text().splitlines():
            if "=" in line and not line.strip().startswith("#"):
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip().strip('"'))


def build_everything() -> dict:
    t = M.load_tables()
    u = M.utilisation(t)
    p = M.project_metrics(t)
    trend = M.monthly_trend(t)
    summary = M.portfolio_summary(p, u)
    facts = {
        "summary": summary,
        "projects": M.project_facts(p, t, u),
        "resource_conflicts": [
            {"name": r["name"], "role": r["role"], "utilisation_pct": int(r["utilisation_pct"]), "projects": int(r["projects"])}
            for _, r in u[u["utilisation_pct"] > 110].sort_values("utilisation_pct", ascending=False).iterrows()
        ],
    }
    return {"tables": t, "util": u, "metrics": p, "trend": trend, "summary": summary, "facts": facts}


def write_outputs(b: dict, report_md: str, provider: str) -> None:
    proc = ROOT / "data" / "processed"
    proc.mkdir(parents=True, exist_ok=True)
    p = b["metrics"].copy()
    p["escalation_reasons"] = p["escalation_reasons"].map("; ".join)
    p.to_csv(proc / "project_metrics.csv", index=False)
    b["util"].to_csv(proc / "resource_utilisation.csv", index=False)
    b["trend"].to_csv(proc / "monthly_trend.csv", index=False)
    (ROOT / "outputs").mkdir(exist_ok=True)
    (ROOT / "outputs" / "portfolio_facts.json").write_text(json.dumps(b["facts"], indent=2, ensure_ascii=False), encoding="utf-8")
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "generated-report.md").write_text(report_md + f"\n---\n_Provider: {provider}_\n", encoding="utf-8")
    write_dashboard_data(b)


def write_dashboard_data(b: dict) -> None:
    facts, t, u, trend = b["facts"], b["tables"], b["util"], b["trend"]
    raid = t["raid"].copy()
    for c in ("due_date", "raised_date"):
        raid[c] = raid[c].dt.date.astype(str)
    projects = []
    for f in facts["projects"]:
        tr = trend[trend["project_id"] == f["project_id"]]
        row = b["metrics"][b["metrics"]["project_id"] == f["project_id"]].iloc[0]
        projects.append({**f,
                         "scores": {k: round(float(row[f"score_{k}"])) for k in M.WEIGHTS},
                         "summary": G.project_summary(f),
                         "recommendations": G.recommendations(f),
                         "trend": [{"m": r["month_end"].strftime("%Y-%m"), "spi": None if r["spi"] != r["spi"] else round(r["spi"], 2),
                                    "cpi": None if r["cpi"] != r["cpi"] else round(r["cpi"], 2)} for _, r in tr.iterrows()]})
    data = {
        "summary": facts["summary"],
        "projects": projects,
        "resources": [{"name": r["name"], "role": r["role"], "capacity": r["capacity_fte"], "allocated": round(r["allocation_fte"], 2),
                       "utilisation_pct": int(r["utilisation_pct"]), "status": r["status"], "projects": int(r["projects"])}
                      for _, r in u.sort_values("utilisation_pct", ascending=False).iterrows()],
        "raid": json.loads(raid.where(raid.notna(), None).to_json(orient="records")),
    }
    (ROOT / "data.js").write_text("// Generated by src/run_pipeline.py - do not edit.\nwindow.PORTFOLIO = "
                                  + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", default="auto", choices=["auto", "offline", "openai", "anthropic"])
    args = ap.parse_args()
    load_dotenv()
    b = build_everything()
    md, used = G.generate_report(b["facts"], args.provider)
    problems = G.verify_numbers(md, b["facts"])
    write_outputs(b, md, used)
    print(f"Projects: {b['summary']['projects']} | RAG: {b['summary']['rag_counts']} | escalations: {b['summary']['escalations']}")
    print(f"Report written with provider '{used}' -> reports/generated-report.md")
    print("Number check:", "all figures traceable to the facts" if not problems else f"UNVERIFIED figures: {problems}")


if __name__ == "__main__":
    main()
